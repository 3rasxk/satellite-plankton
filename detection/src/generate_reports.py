def format_cell_count(cc: dict) -> str:
    if cc["raw"] == "":
        return "(not reported)"
    if cc["lower"] == cc["upper"]:
        return f"{cc['raw']}"
    return f"{cc['raw']} (midpoint {cc['representative']:,.0f})"


def format_satellite_status(row: dict) -> str:
    """One-cell honest summary of the real satellite-attempt outcome for
    a matchable row -- distinct real reasons (pre-Sentinel-2-era, cloud
    rejection, no-scenes tiling gap, land/water mask) must stay
    distinguishable, not collapsed into one generic 'no data'."""
    if not row["matchable"]:
        return "n/a (no coordinate)"
    s2 = row["sentinel2_status"]
    clim = row["climatology_status"]
    if s2 == "ok" and clim == "ok":
        return "ok"
    parts = []
    if s2 == "no_imagery":
        parts.append(f"S2: no cloud-free scene ({row['sentinel2_error']})")
    elif s2 == "no_water_pixels":
        parts.append(f"S2: land/water mask rejected buffer ({row['sentinel2_error']})")
    elif s2 == "ok":
        parts.append("S2: ok")
    if clim == "no_data":
        parts.append("MODIS climatology: archive gap at this location/window")
    elif clim == "ok":
        parts.append("MODIS climatology: ok")
    return "; ".join(parts) if parts else "n/a"


def write_event_table(result: dict) -> None:
    """Publish real index availability separately from disabled evaluation."""
    lines = [
        "# Event table -- all 14 documented Thai events",
        "",
        "Generated by `detection/src/generate_reports.py` from a live run of "
        "`detection/src/thresholds.py` against `data/validation/events.csv`. "
        "MODIS chlor_a climatology is independent concentration context, "
        "not a baseline for the spectral indices.",
        "",
        f"{result['n_matchable']} of {result['n_events']} events have coordinates; "
        f"{result['n_with_real_reading']} produced real index readings. "
        f"All {result['n_events']} events cannot be evaluated for detection. "
        "**Not computed — no valid baseline exists.**",
        "",
        "| event_id | date | date precision | location | location_precision | species | "
        "cell_count | matchable | satellite status | index (primary=ndci) | actual_date | "
        "evaluation | low evidentiary weight | notes |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for row in result["rows"]:
        idx = row["index_values"]
        ndci = f"{idx['ndci']:.4f}" if idx else "n/a"
        cells = [
            row["event_id"], row["date_display"], row["date_precision_tier"],
            row["location_name"], row["location_precision"], row["species"],
            format_cell_count(row["cell_count"]),
            "yes" if row["matchable"] else "no", format_satellite_status(row),
            ndci, row["actual_date"] or "n/a", "cannot be evaluated",
            "yes" if row["low_weight"] else "",
            row["match_reason"].replace("\n", " "),
        ]
        lines.append("| " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Satellite-attempt detail",
        "",
        "Search windows derive from each event's recorded dates, with the same cloud "
        "margin for every event. Neither coordinates nor windows are tuned per event.",
        "",
        "| event_id | target_date | search_window_days (+/-) | Sentinel-2 result | "
        "actual_date | MODIS climatology result |",
        "|---|---|---|---|---|---|",
    ]
    for row in result["rows"]:
        if not row["matchable"]:
            continue
        s2 = row["sentinel2_status"]
        if row["sentinel2_error"]:
            s2 += f" -- {row['sentinel2_error']}"
        lines.append(
            f"| {row['event_id']} | {row['target_date']} | {row['search_window_days']} | "
            f"{s2} | {row['actual_date'] or 'n/a'} | {row['climatology_status']} |"
        )

    lines += [
        "",
        "## th_001 regional-proxy attempt",
        "",
        "This study-area-scale proxy does not supply an event coordinate.",
        "",
    ]
    proxy = result["th001_proxy"]
    if proxy is not None:
        for note in proxy["notes"]:
            lines.append(f"- {note}")
    lines += [
        "",
        f"## Leave-one-out calibration ({len(result['loo_results'])} held-out units)",
        "",
        "Same-episode clusters remain grouped. No held-out unit can be scored: "
        "no valid baseline exists, including for events with real index readings.",
        "",
        "| iteration | held-out event(s) | evaluation | reason |",
        "|---|---|---|---|",
    ]
    for iteration in result["loo_results"]:
        lines.append(
            f"| {iteration['label']} | {', '.join(iteration['held_out_ids'])} | "
            f"cannot be evaluated | {iteration['reason']} |"
        )
    lines += [
        "",
        "## Interpretation",
        "",
        "th_010 is an index reading, not a hit or miss. Its three reading qualifiers "
        "remain: n=1; karenia_sp rather than the Noctiluca target; and recovery only "
        "through the ETOPO1 fallback at a difficult shoreline buffer. JRC returns "
        "zero pixels, ETOPO1 averages +3.1 m while placing about 35% below sea level, "
        "and bands are 1040–1660 against "
        "200–560 for open Gulf water. See LIMITATIONS.md §1.",
        "",
        "Historical low-weight events remain listed separately. No detection rates, "
        "cutoff performance, or calibrated thresholds can be inferred from this table.",
    ]
    (REPORTS_DIR / "event_table.md").write_text("\n".join(lines) + "\n")


def write_index_comparison(demo_results: list[dict]) -> None:
    lines = [
        "# Index comparison -- NDCI vs 2BDA vs 3BDA vs B2/B3",
        "",
        "**All 14 events cannot be evaluated for detection.** No valid anomaly "
        "baseline exists for the spectral indices. The former comparison with "
        "a MODIS `chlor_a` concentration baseline mixed incompatible units and "
        "supplies no result for any index. th_010 has a satellite reading but "
        "no valid anomaly statistic; it is not a miss. The non-event readings "
        "below demonstrate that the index functions ran on real Sentinel-2 "
        "data, **not that their outputs detect blooms or rank the indices**.",
        "",
        "| point | date | actual_date | cloud_fraction | NDCI | 2BDA | 3BDA | B2/B3 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for d in demo_results:
        if d["status"] != "ok":
            lines.append(
                f"| {d['label']} | {d['requested_date']} | -- | -- | -- | -- | -- | -- "
                f"({d['status']}: {d['reason']}) |"
            )
            continue
        idx = d["index_values"]
        lines.append(
            "| {label} | {req} | {actual} | {cf:.2f} | {ndci:.4f} | {bda2:.4f} | "
            "{bda3:.4f} | {ratio:.4f} |".format(
                label=d["label"],
                req=d["requested_date"],
                actual=d["actual_date"],
                cf=d["cloud_fraction"],
                ndci=idx["ndci"],
                bda2=idx["2bda"],
                bda3=idx["3bda"],
                ratio=idx["b2_b3_ratio"],
            )
        )

    lines += [
        "",
        "## Satellite availability is separate from anomaly evaluation",
        "",
        "Seven of the 14 events have coordinates. The recorded satellite checks "
        "recovered th_010 on `actual_date` 2020-02-16; of the other six, four "
        "predate Sentinel-2, one has a coverage gap, and one has total cloud "
        "rejection. The remaining seven have no coordinate. **All 14 lack a "
        "valid anomaly statistic**, independently of these availability "
        "findings. th_010's reading has three qualifiers: `n=1`; `karenia_sp`, "
        "not the B2/B3 *Noctiluca* target; and recovery through the ETOPO1 "
        "fallback where JRC returns zero pixels, ETOPO1 averages +3.1 m with "
        "about 35% below sea level, and bands are 1040–1660 versus 200–560 in "
        "open Gulf water. None changes the invalid statistic into a result.",
        "",
        "## What these numbers do and don't show",
        "",
        "- Confirms all four index functions in `src/indices.py` run against real "
        "band values pulled live from Google Earth Engine (`COPERNICUS/S2_SR_HARMONIZED`) "
        "-- not synthetic test fixtures.",
        "- Does NOT show which index best discriminates a documented bloom. "
        "No valid anomaly statistic exists for any of the 14 events, and none "
        "of the demo points/dates is a documented event.",
        "- The proposed benefit of 3BDA near turbid river mouths remains "
        "unvalidated here. th_003/th_008/th_012 at Tha Chin all predate "
        "Sentinel-2, and no event has an evaluable anomaly statistic.",
        "- B2/B3 (green *Noctiluca* discrimination) is secondary/lower-confidence by "
        "design (`.claude/agents/bloom-detection.md` §1) and, per "
        "`data/validation/CALIBRATION_NOTES.md` §2, is only expected to be meaningful "
        "for *Noctiluca* events specifically -- none of the demo points above are "
        "events at all, so this column is shown only to confirm the function runs, "
        "not that it discriminates anything.",
    ]

    (REPORTS_DIR / "index_comparison.md").write_text("\n".join(lines) + "\n")


def write_threshold_sweep_plot(result: dict, demo_results: list[dict]) -> None:
    """Replace the former cutoff illustration with the actual disabled state."""
    fig, ax = plt.subplots(figsize=(9, 3))
    ax.axis("off")
    ax.text(
        0.5, 0.65, "Threshold evaluation cannot be performed",
        ha="center", va="center", fontsize=17,
    )
    ax.text(
        0.5, 0.35,
        f"All {result['n_events']} validation events: cannot be evaluated.\n"
        "Not computed — no valid baseline exists for the spectral indices.",
        ha="center", va="center", fontsize=12,
    )
    fig.tight_layout()
    fig.savefig(REPORTS_DIR / "threshold_sweep.png", dpi=150)
    plt.close(fig)


def main() -> None:
    REPORTS_DIR.mkdir(exist_ok=True)

    print("Running thresholds.run() (real GEE calls for th_001 regional proxy)...")
    result = run_thresholds()

    print("Running demo-point index comparison (real GEE calls)...")
    demo = []
    for p in DEMO_POINTS:
        from _data_pipeline import get_sentinel2_bands

        try:
            bands = get_sentinel2_bands(p["lat"], p["lng"], p["date"])
            idx = compute_all_indices(bands)
            demo.append(
                {
                    "label": p["label"],
                    "requested_date": p["date"],
                    "actual_date": bands["actual_date"],
                    "cloud_fraction": bands["cloud_fraction"],
                    "status": "ok",
                    "reason": None,
                    "index_values": idx,
                }
            )
        except Exception as exc:  # noqa: BLE001 - report-generation context, not pipeline code
            demo.append(
                {
                    "label": p["label"],
                    "requested_date": p["date"],
                    "actual_date": None,
                    "cloud_fraction": None,
                    "status": "error",
                    "reason": str(exc),
                    "index_values": None,
                }
            )

    write_event_table(result)
    write_index_comparison(demo)
    write_threshold_sweep_plot(result, demo)
    print(f"Wrote reports to {REPORTS_DIR}")


if __name__ == "__main__":
    main()
