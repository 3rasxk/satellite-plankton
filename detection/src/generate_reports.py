def format_cell_count(cc: dict) -> str:
    if cc["raw"] == "":
        return "(not reported)"
    if cc["lower"] == cc["upper"]:
        return f"{cc['raw']}"
    return f"{cc['raw']} (midpoint {cc['representative']:,.0f})"


def write_event_table(result: dict) -> None:
    lines = [
        "# Event table -- all 14 documented Thai events",
        "",
        "Generated by `detection/src/generate_reports.py` from a live run of "
        "`detection/src/thresholds.py` against `data/validation/events.csv`. "
        "See `data/validation/CALIBRATION_NOTES.md` for the methodology "
        "decisions encoded in every column below.",
        "",
        f"**Headline result: {result['n_matchable']} of {result['n_events']} events had "
        f"lat/lng in events.csv. {result['n_with_real_reading']} of {result['n_events']} "
        "events produced a real satellite reading in this run** (th_001, via a "
        "regional-proxy attempt -- see the note under the table; even that attempt "
        "did not yield a usable Sentinel-2 image, and the reported reading below "
        "for th_001 is `not applicable`).",
        "",
        "| event_id | date | date precision | location | location_precision | species | "
        "cell_count | matchable | index (primary=ndci) | anomaly_z | flagged | "
        "low evidentiary weight | notes |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for row in result["rows"]:
        idx = row["index_values"]
        ndci_val = f"{idx['ndci']:.4f}" if idx else "n/a"
        z = row["z_scores"]["ndci"]["z"] if row["z_scores"] and row["z_scores"].get("ndci") else None
        z_display = f"{z:.2f}" if z is not None else "n/a"
        flagged_display = (
            "yes" if row["flagged"] is True else "no" if row["flagged"] is False else "n/a"
        )
        lines.append(
            "| {eid} | {date} | {prec} | {loc} | {locprec} | {species} | {cc} | "
            "{matchable} | {ndci} | {z} | {flagged} | {loweight} | {notes} |".format(
                eid=row["event_id"],
                date=row["date_display"],
                prec=row["date_precision_tier"],
                loc=row["location_name"],
                locprec=row["location_precision"],
                species=row["species"],
                cc=format_cell_count(row["cell_count"]),
                matchable="yes" if row["matchable"] else "no",
                ndci=ndci_val,
                z=z_display,
                flagged=flagged_display,
                loweight="yes" if row["low_weight"] else "",
                notes=row["match_reason"].replace("\n", " "),
            )
        )

    lines += [
        "",
        "## th_001 regional-proxy attempt -- detail",
        "",
        "th_001 is the only row whose location is recorded at the scale of the "
        "whole study area (\"upper Gulf of Thailand\") rather than a named site, "
        "so a regional-proxy open-water point was tried as a same-scale check -- "
        "explicitly not a claim about th_001's exact pixel. Live result from this run:",
        "",
    ]
    proxy = result["th001_proxy"]
    if proxy is not None:
        lines.append(f"- Points attempted: {', '.join(proxy['attempted_points'])}")
        for note in proxy["notes"]:
            lines.append(f"- {note}")
        if proxy["sentinel2"] is None:
            lines.append(
                "- **Sentinel-2: no usable image found** at either candidate point within "
                "a 25-day window of 2018-07-30 -- zero scenes returned by the collection "
                "query, not a cloud rejection."
            )
        if proxy["modis_climatology"] is None:
            lines.append(
                "- **MODIS chlor_a: no observation within +/-15 days of 2018-07-30** at "
                "either candidate point in the full 2002-present archive -- a genuine "
                "monsoon-season data gap (docs/DETECTION_PLAN.md §8), not a query error."
            )
    lines += [
        "",
        "## Leave-one-out calibration (12 iterations: 10 single events + 2 clusters)",
        "",
        "Per `data/validation/CALIBRATION_NOTES.md` §1, th_005/th_006/th_007 (Aug 2019 "
        "Chonburi episode) and th_009/th_010 (Feb 2020 Chonburi episode) are held out as "
        "single units, never split.",
        "",
        "| iteration | held-out event(s) | caught | reason |",
        "|---|---|---|---|",
    ]
    for it in result["loo_results"]:
        caught_display = "yes" if it["caught"] is True else "no" if it["caught"] is False else "n/a (could not run)"
        lines.append(
            f"| {it['label']} | {', '.join(it['held_out_ids'])} | {caught_display} | {it['reason']} |"
        )

    lines += [
        "",
        "## Reading this table honestly",
        "",
        "- **0 of 14 events have lat/lng in `events.csv`.** Per `docs/DETECTION_PLAN.md` "
        "§3, a coordinate is never invented for a named place -- this is reported as a "
        "finding, not patched around.",
        "- The one attempted exception (th_001, regional proxy) found no usable "
        "Sentinel-2 scene and a real ~2-month MODIS data gap around the event date -- "
        "also a finding, not a bug.",
        "- Every leave-one-out iteration above therefore reports `caught = n/a` for the "
        "same underlying reason: no real satellite reading was available for any member "
        "of that held-out unit.",
        "- th_012/th_013/th_014 (marked in the low-evidentiary-weight column) are "
        "pre-monitoring-era with no cell count in any source "
        "(`data/validation/CALIBRATION_NOTES.md` §3) -- shown in the table for "
        "completeness, never averaged into a headline number with the 9 "
        "cell-count-bearing events.",
        "- **No percentage is reported anywhere in this table or this file, by design** "
        "(CLAUDE.md truth boundary, `.claude/agents/bloom-detection.md` "
        "\"Non-negotiable rules\").",
    ]

    (REPORTS_DIR / "event_table.md").write_text("\n".join(lines) + "\n")


def write_index_comparison(demo_results: list[dict]) -> None:
    lines = [
        "# Index comparison -- NDCI vs 2BDA vs 3BDA vs B2/B3",
        "",
        "**Cannot be compared against the 14 validation events** -- see "
        "`event_table.md`: 0 of 14 events produced a real matched satellite "
        "reading in this run, so there is no per-event ground truth to score "
        "any index against yet. What follows instead is a live demonstration "
        "that all four indices compute correctly on real Sentinel-2 data, at "
        "non-event points/dates chosen only because they returned cloud-clear "
        "imagery during this build -- **not a validation result.**",
        "",
        "| point | date | actual_date | cloud_fraction | NDCI | 2BDA | 3BDA | B2/B3 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for d in demo_results:
        if d["status"] != "ok":
            lines.append(
                f"| {d['label']} | {d['requested_date']} | -- | -- | -- | -- | -- | -- "
                f"({d['status']}: {d['reason']}) |"
            )
            continue
        idx = d["index_values"]
        lines.append(
            "| {label} | {req} | {actual} | {cf:.2f} | {ndci:.4f} | {bda2:.4f} | "
            "{bda3:.4f} | {ratio:.4f} |".format(
                label=d["label"],
                req=d["requested_date"],
                actual=d["actual_date"],
                cf=d["cloud_fraction"],
                ndci=idx["ndci"],
                bda2=idx["2bda"],
                bda3=idx["3bda"],
                ratio=idx["b2_b3_ratio"],
            )
        )

    lines += [
        "",
        "## What these numbers do and don't show",
        "",
        "- Confirms all four index functions in `src/indices.py` run against real "
        "band values pulled live from Google Earth Engine (`COPERNICUS/S2_SR_HARMONIZED`) "
        "-- not synthetic test fixtures.",
        "- Does NOT show which index best discriminates a real documented bloom, "
        "because none of the three points/dates above coincide with a documented event "
        "(`data/validation/events.csv` has no matchable coordinate for comparison, per "
        "`event_table.md`).",
        "- Per `docs/DETECTION_PLAN.md` §2, 3BDA is expected to outperform NDCI/2BDA "
        "specifically near river mouths (turbid water) -- untested here for the same "
        "reason: no real event coordinate near a river mouth was available to check "
        "against.",
        "- B2/B3 (green *Noctiluca* discrimination) is secondary/lower-confidence by "
        "design (`.claude/agents/bloom-detection.md` §1) and, per "
        "`data/validation/CALIBRATION_NOTES.md` §2, is only expected to be meaningful "
        "for *Noctiluca* events specifically -- none of the demo points above are "
        "events at all, so this column is shown only to confirm the function runs, "
        "not that it discriminates anything.",
    ]

    (REPORTS_DIR / "index_comparison.md").write_text("\n".join(lines) + "\n")


def write_threshold_sweep_plot(result: dict, demo_results: list[dict]) -> None:
    """threshold_sweep.png -- honest about what it is. Left panel: the
    real per-event match/no-match outcome for all 14 events (actual data
    from this run). Right panel: the config.yaml default z-score cutoffs
    plotted against a standard normal curve, explicitly captioned as
    illustrative/uncalibrated -- NOT an empirical sensitivity/false-alarm
    sweep, because (left panel shows why) there was no real per-event
    data to sweep against."""
    import numpy as np

    fig, axes = plt.subplots(1, 2, figsize=(12, 5))

    # Left: match status per event, real data from this run.
    ax = axes[0]
    labels = [r["event_id"] for r in result["rows"]]
    status = []
    for r in result["rows"]:
        if r["index_values"] is not None:
            status.append(2)  # real reading obtained
        elif r["event_id"] == "th_001":
            status.append(1)  # attempted, no data
        else:
            status.append(0)  # unmatched, no coordinate
    colors = {0: "#b0b0b0", 1: "#e0952b", 2: "#2b8a3e"}
    ax.bar(labels, [1] * len(labels), color=[colors[s] for s in status])
    ax.set_ylim(0, 1.2)
    ax.set_yticks([])
    ax.set_title("Per-event satellite match status (real, this run)")
    ax.tick_params(axis="x", rotation=90)
    from matplotlib.patches import Patch

    ax.legend(
        handles=[
            Patch(color=colors[0], label="No coordinate (unmatched)"),
            Patch(color=colors[1], label="Regional proxy attempted, no data"),
            Patch(color=colors[2], label="Real reading obtained"),
        ],
        loc="upper right",
        fontsize=8,
    )

    # Right: illustrative, uncalibrated cutoffs. NOT a sensitivity curve.
    ax2 = axes[1]
    x = np.linspace(-4, 4, 400)
    y = np.exp(-(x**2) / 2) / np.sqrt(2 * np.pi)
    ax2.plot(x, y, color="#444444", label="Standard normal (illustrative anomaly distribution)")
    cfg = result["config"]["thresholds"]["ndci"]
    ax2.axvline(cfg["elevated_z"], color="#e0952b", linestyle="--", label=f"elevated (z>={cfg['elevated_z']})")
    ax2.axvline(cfg["warning_z"], color="#c92a2a", linestyle="--", label=f"warning (z>={cfg['warning_z']})")
    ax2.set_title("config.yaml default cutoffs (UNCALIBRATED -- see caption)")
    ax2.set_xlabel("anomaly z-score")
    ax2.legend(fontsize=8)

    fig.suptitle(
        "detection/src/config.yaml thresholds are literature defaults, not empirically "
        "calibrated -- 0 of 14 events had a matchable coordinate this run (see left panel "
        "and reports/event_table.md). This is NOT a sensitivity/false-alarm sweep.",
        fontsize=9,
        wrap=True,
    )
    fig.tight_layout(rect=[0, 0, 1, 0.90])
    fig.savefig(REPORTS_DIR / "threshold_sweep.png", dpi=150)
    plt.close(fig)


def main() -> None:
    REPORTS_DIR.mkdir(exist_ok=True)

    print("Running thresholds.run() (real GEE calls for th_001 regional proxy)...")
    result = run_thresholds()

    print("Running demo-point index comparison (real GEE calls)...")
    demo = []
    for p in DEMO_POINTS:
        from _data_pipeline import get_sentinel2_bands

        try:
            bands = get_sentinel2_bands(p["lat"], p["lng"], p["date"])
            idx = compute_all_indices(bands)
            demo.append(
                {
                    "label": p["label"],
                    "requested_date": p["date"],
                    "actual_date": bands["actual_date"],
                    "cloud_fraction": bands["cloud_fraction"],
                    "status": "ok",
                    "reason": None,
                    "index_values": idx,
                }
            )
        except Exception as exc:  # noqa: BLE001 - report-generation context, not pipeline code
            demo.append(
                {
                    "label": p["label"],
                    "requested_date": p["date"],
                    "actual_date": None,
                    "cloud_fraction": None,
                    "status": "error",
                    "reason": str(exc),
                    "index_values": None,
                }
            )

    write_event_table(result)
    write_index_comparison(demo)
    write_threshold_sweep_plot(result, demo)
    print(f"Wrote reports to {REPORTS_DIR}")


if __name__ == "__main__":
    main()
